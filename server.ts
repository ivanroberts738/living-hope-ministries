// GET Activities
app.get('/api/activities', (req: Request, res: Response) => {
  const db = loadLocalDb();
  let activities = db.activities || [];

  const { status, category, search } = req.query;

  if (status) {
    activities = activities.filter((a: any) => a.status === status);
  } else {
    // By default for public users, show published activities unless specified
    if (req.headers['x-admin-request'] !== 'true') {
      activities = activities.filter((a: any) => a.status === 'published');
    }
  }

  if (category && category !== 'all') {
    activities = activities.filter((a: any) => a.programmeId === category || a.programmeName.toLowerCase().includes((category as string).toLowerCase()));
  }

  if (search) {
    const q = (search as string).toLowerCase();
    activities = activities.filter(
      (a: any) =>
        a.title.toLowerCase().includes(q) ||
        a.description.toLowerCase().includes(q) ||
        a.location.toLowerCase().includes(q) ||
        a.programmeName.toLowerCase().includes(q)
    );
  }

  // Sort newest first
  activities.sort((a: any, b: any) => new Date(b.activityDate).getTime() - new Date(a.activityDate).getTime());

  res.json(activities);
});

