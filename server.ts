// POST Image Upload Endpoint
app.post('/api/upload', (req: Request, res: Response) => {
  const { imageBase64, filename } = req.body;

  if (!imageBase64) {
    return res.status(400).json({ error: 'No image data received' });
  }

  // Handle base64 string
  try {
    const uploadsDir = path.join(process.cwd(), 'public', 'uploads');
    if (!fs.existsSync(uploadsDir)) {
      fs.mkdirSync(uploadsDir, { recursive: true });
    }

    const matches = imageBase64.match(/^data:([A-Za-z-+\/]+);base64,(.+)$/);
    if (!matches || matches.length !== 3) {
      // If it's already a direct URL string, return it back
      if (imageBase64.startsWith('http')) {
        return res.json({ url: imageBase64 });
      }
      return res.status(400).json({ error: 'Invalid base64 format' });
    }

    const ext = matches[1].split('/')[1] || 'jpg';
    const cleanExt = ext.replace('+xml', '');
    const safeFilename = `buhugu_${Date.now()}_${Math.random().toString(36).substring(2, 7)}.${cleanExt}`;
    const filePath = path.join(uploadsDir, safeFilename);

    const buffer = Buffer.from(matches[2], 'base64');
    fs.writeFileSync(filePath, buffer);

    const publicUrl = `/uploads/${safeFilename}`;
    return res.json({ url: publicUrl, filename: safeFilename });
  } catch (err) {
    console.error('Upload handling error:', err);
    return res.status(500).json({ error: 'Failed to save uploaded photograph' });
  }
});

// Start Express + Vite Middleware
async function startServer() {
  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req: Request, res: Response) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Buhugu Living Hope Ministries Server running on http://localhost:${PORT}`);
  });
}

startServer();
