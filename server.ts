// GET Stats
app.get('/api/stats', (req: Request, res: Response) => {
  const db = loadLocalDb();
  const activities = db.activities || [];
  const published = activities.filter((a: any) => a.status === 'published');

  const now = new Date();
  const currentMonth = now.getMonth();
  const currentYear = now.getFullYear();

  const activitiesThisMonth = published.filter((a: any) => {
    const d = new Date(a.activityDate);
    return d.getMonth() === currentMonth && d.getFullYear() === currentYear;
  }).length;

  let totalBeneficiaries = 0;
  let womenReached = 0;
  let childrenReached = 0;

  published.forEach((a: any) => {
    womenReached += Number(a.womenReached || 0);
    childrenReached += Number(a.childrenReached || 0);
    totalBeneficiaries += Number(a.beneficiariesTotal || (a.womenReached + a.childrenReached + (a.otherBeneficiaries || 0)));
  });

  res.json({
    totalActivities: published.length,
    activitiesThisMonth,
    womenReached,
    childrenReached,
    communitiesReached: 8, // Sironko & Bulambuli sub-counties
    totalPhotos: db.gallery ? db.gallery.length : 0,
    totalBeneficiaries
  });
});

